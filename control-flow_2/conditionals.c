// IF STATEMENT 
int age = 18;

if (age >= 18) {
  printf("You are an adult");
}


// IF - ELSE
int age = 16;

if (age >= 18) {
  printf("Adult");
} else {
  printf("Not adult");
}


// ELSE IF
int score = 75;

if (score >= 90) {
  printf("A");
} else if (score >= 70) {
  printf("B");
} else {
  printf("C");
}


// SWITCH
int day = 2;

switch(day) {
  case 1:
      printf("Monday");
      break;
  case 2:
      printf("Tuesday");
      break;
  default:
      printf("invalid day");
}

